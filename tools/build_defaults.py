#!/usr/bin/env python3
"""Regenerates assets/defaults.js and assets/fonts.js from the source files.

The tool runs straight from file:// (double-click index.html), where browsers
block fetch()/XHR of local files, so the default DXF, the original wordmark and
the bundled fonts are embedded as JavaScript.

Usage (from the project folder):  python3 tools/build_defaults.py
"""
import base64, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SVG = os.path.join(ROOT, "allRuler.svg")
DXF = os.path.join(ROOT, "inchworm_v8_noKerf_simplified.dxf")

# The Figma frame is 466 x 615 units for a 3in x 4in card.
CARD_W_MM, CARD_H_MM = 76.2, 101.6
SX, SY = CARD_W_MM / 466.0, CARD_H_MM / 615.0


def wordmark_from_svg():
    s = open(SVG, encoding="utf-8").read()
    strokes = []
    width_u = None
    for m in re.finditer(r'<path d="([^"]*)" stroke-width="([\d.]+)"[^>]*stroke="black"', s):
        d, sw = m.group(1), float(m.group(2))
        width_u = sw
        nums = [float(n) for n in re.findall(r"-?\d*\.?\d+(?:e-?\d+)?", d)]
        pts = []
        for i in range(0, len(nums) - 1, 2):
            pts.append([round(nums[i] * SX, 4), round(CARD_H_MM - nums[i + 1] * SY, 4)])
        strokes.append(pts)
    return {"strokes": strokes, "strokeWidth": round(width_u * SX, 4)}


def main():
    wm = wordmark_from_svg()
    dxf_text = open(DXF, encoding="utf-8", errors="replace").read()
    with open(os.path.join(ROOT, "assets", "defaults.js"), "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by tools/build_defaults.py - do not edit by hand.\n")
        f.write("window.PP = window.PP || {};\n")
        f.write("PP.DEFAULT_WORDMARK = " + json.dumps(wm, separators=(",", ":")) + ";\n")
        f.write("PP.DEFAULT_DXF_NAME = " + json.dumps(os.path.basename(DXF)) + ";\n")
        f.write("PP.DEFAULT_DXF = " + json.dumps(dxf_text) + ";\n")

    # (id, display name, file, monospace?)  Monospace fonts are offered for the ruler numbers.
    fonts = [
        ("inter-600", "Inter SemiBold (original)", "inter-600.woff", False),
        ("inter-400", "Inter Regular", "inter-400.woff", False),
        ("inter-800", "Inter ExtraBold", "inter-800.woff", False),
        ("space-mono-400", "Space Mono", "space-mono-400.woff", True),
        ("space-mono-700", "Space Mono Bold", "space-mono-700.woff", True),
        ("jetbrains-mono-400", "JetBrains Mono", "jetbrains-mono-400.woff", True),
        ("jetbrains-mono-600", "JetBrains Mono SemiBold", "jetbrains-mono-600.woff", True),
        ("jetbrains-mono-800", "JetBrains Mono ExtraBold", "jetbrains-mono-800.woff", True),
        ("ibm-plex-mono-400", "IBM Plex Mono", "ibm-plex-mono-400.woff", True),
        ("ibm-plex-mono-600", "IBM Plex Mono SemiBold", "ibm-plex-mono-600.woff", True),
        ("roboto-mono-500", "Roboto Mono Medium", "roboto-mono-500.woff", True),
        ("fira-code-500", "Fira Code Medium", "fira-code-500.woff", True),
        ("dm-mono-500", "DM Mono Medium", "dm-mono-500.woff", True),
        ("share-tech-mono-400", "Share Tech Mono", "share-tech-mono-400.woff", True),
        ("permanent-marker", "Permanent Marker", "permanent-marker.woff", False),
        ("caveat-brush", "Caveat Brush", "caveat-brush.woff", False),
        ("rubik-mono-one", "Rubik Mono One", "rubik-mono-one.woff", False),
        ("bungee", "Bungee", "bungee.woff", False),
    ]
    with open(os.path.join(ROOT, "assets", "fonts.js"), "w", encoding="utf-8") as f:
        f.write("// AUTO-GENERATED by tools/build_defaults.py - bundled OFL fonts (fontsource).\n")
        f.write("window.PP = window.PP || {};\nPP.BUNDLED_FONTS = [\n")
        for fid, name, fn, mono in fonts:
            b64 = base64.b64encode(open(os.path.join(ROOT, "fonts", fn), "rb").read()).decode()
            f.write("  " + json.dumps({"id": fid, "name": name, "mono": mono, "data": b64}) + ",\n")
        f.write("];\n")

    xs = [p[0] for s in wm["strokes"] for p in s]
    ys = [p[1] for s in wm["strokes"] for p in s]
    print("wordmark centerline bbox mm: x %.3f..%.3f  y %.3f..%.3f  stroke %.3f" % (
        min(xs), max(xs), min(ys), max(ys), wm["strokeWidth"]))
    print("center %.3f, %.3f  width %.3f" % ((min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2, max(xs) - min(xs)))


if __name__ == "__main__":
    main()
